// Rebuild the offline structural validator from the pinned OAI schema with Ajv 8.20.0.
// Usage: node build-openapi-3.1-validator.js <path-to-ajv-package>
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ajvPackage = process.argv[2];
if (!ajvPackage) throw new Error('Pass the Ajv 8.20.0 package directory.');
const version = require(path.join(ajvPackage, 'package.json')).version;
if (version !== '8.20.0') throw new Error(`Expected Ajv 8.20.0, got ${version}`);
const Ajv2020 = require(path.join(ajvPackage, 'dist/2020'));
const standaloneCode = require(path.join(ajvPackage, 'dist/standalone')).default;

const sourcePath = path.join(__dirname, 'openapi-3.1-2026-08-03.schema.json');
const outputPath = path.join(__dirname, 'auth-user-friend.openapi.validator.js');
const source = fs.readFileSync(sourcePath);
const schema = JSON.parse(source);
if (schema.$id !== 'https://spec.openapis.org/oas/3.1/schema/2026-08-03') {
  throw new Error('Unexpected official OpenAPI schema identifier.');
}

// The OAI structural schema uses #meta dynamic references so it can be extended
// by a Schema Object dialect. This task validates OAS structure without changing
// its Schema Object dialect. Ajv 8.20.0 resolves those references to the root
// during compilation, so pin them to OAI's own $defs/schema placeholder.
let replacements = 0;
function pinSchemaReferences(node) {
  if (!node || typeof node !== 'object') return;
  if (node.$dynamicRef === '#meta') {
    delete node.$dynamicRef;
    node.$ref = '#/$defs/schema';
    replacements++;
  }
  for (const value of Object.values(node)) pinSchemaReferences(value);
}
pinSchemaReferences(schema);
if (replacements !== 4) throw new Error(`Expected four Schema Object references, got ${replacements}`);

const ajv = new Ajv2020({ strict: false, allErrors: true, validateFormats: false, code: { source: true } });
const validate = ajv.compile(schema);
const canonical = JSON.parse(fs.readFileSync(path.join(__dirname, 'auth-user-friend.openapi.json')));
if (!validate(canonical)) throw new Error(`Canonical API rejected: ${JSON.stringify(validate.errors?.slice(0, 5))}`);
const derivedSchemaHash = crypto.createHash('sha256').update(JSON.stringify(schema)).digest('hex');
const sourceHash = crypto.createHash('sha256').update(source).digest('hex');
const header = `// Generated by build-openapi-3.1-validator.js with Ajv ${version}.\n` +
  `// OAI source SHA-256: ${sourceHash}\n` +
  `// Adapted schema JSON SHA-256: ${derivedSchemaHash}\n`;
fs.writeFileSync(outputPath, header + standaloneCode(ajv, validate));
console.log(`Built ${path.basename(outputPath)} from OAI source ${sourceHash}; adapted schema ${derivedSchemaHash}; dynamic references pinned=${replacements}`);
